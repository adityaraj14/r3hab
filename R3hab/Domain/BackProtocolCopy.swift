import Foundation

/// Condensed non-specific low back protocol.
/// Framing: NSLBP guidelines first (stay active, exercise, no single best modality);
/// E3-style side-bend / hip-extension menu is practical 80/20 programming — not a QL-only claim.
/// Not medical advice.
enum BackProtocolCopy {
    static let title = "Low back · trunk capacity"

    static let summary = """
    Most one-sided low back pain is non-specific: no single structure needs to be “fixed.” Guidelines (NICE / APTA-style) emphasize staying active, graded exercise, and avoiding long bed rest. The QL is often blamed for flank or side-bend pain, but the exact tissue is hard to isolate — rehab still works by rebuilding capacity, not by chasing a perfect diagnosis.
    """

    static let program = """
    Principles first
    • Keep walking most days as tolerated (primary “dose” of movement).
    • Temporarily ease sharp aggravators; don’t stop all activity.
    • Rebuild side-bend and hip-extension capacity with holds, then slow dynamic work.
    • Progress one variable at a time (hold length → ROM → load). Think months, not days.
    • Soft-cut if next-day back pain is clearly worse after a session.

    80/20 exercise menu (2–3×/week, both sides when applicable)
    Built from practical trunk programming (e.g. E3-style QL / side-bend work) — a useful menu, not the only proven protocol:
    • Side plank holds 2–3×30–60s (or suitcase hold / farmer carry)
    • Hip thrust or bridge 2–3×8–15 (or extension holds if moving is too hot)

    Irritable flare
    Easy walk, gentle cat-cow / rotations; skip hard side-bend load for a few days, then rebuild.
    """

    static let redFlags = """
    Seek care urgently for progressive leg weakness/numbness, bowel/bladder change, fever, unexplained weight loss, night pain that doesn’t settle, or pain after significant trauma.
    """
}
